(function renderGallery() {
  const params = new URLSearchParams(window.location.search);
  const selected = params.get('set') || TWT_GALLERIES[0].id;
  const gallery = TWT_GALLERIES.find(item => item.id === selected);
  const title = document.getElementById('galleryTitle');
  const intro = document.getElementById('galleryIntro');
  const hero = document.getElementById('galleryHero');
  const heading = document.getElementById('galleryHeading');
  const count = document.getElementById('galleryCount');
  const description = document.getElementById('galleryDescription');
  const grid = document.getElementById('galleryGrid');
  const empty = document.getElementById('galleryEmpty');
  const lightbox = document.createElement('div');
  lightbox.className = 'gallery-lightbox';
  lightbox.setAttribute('aria-hidden', 'true');
  lightbox.innerHTML = '<div class="gallery-lightbox-inner"><button class="gallery-lightbox-close" type="button" aria-label="Close image">&times;</button><img alt=""></div>';
  document.body.appendChild(lightbox);
  const lightboxImg = lightbox.querySelector('img');
  const lightboxClose = lightbox.querySelector('.gallery-lightbox-close');

  function openLightbox(src, alt) {
    lightboxImg.src = src;
    lightboxImg.alt = alt;
    lightbox.classList.add('open');
    lightbox.setAttribute('aria-hidden', 'false');
    document.body.classList.add('lightbox-open');
  }

  function closeLightbox() {
    lightbox.classList.remove('open');
    lightbox.setAttribute('aria-hidden', 'true');
    document.body.classList.remove('lightbox-open');
    lightboxImg.removeAttribute('src');
  }

  lightboxClose.addEventListener('click', closeLightbox);
  lightbox.addEventListener('click', event => {
    if (event.target === lightbox) closeLightbox();
  });
  document.addEventListener('keydown', event => {
    if (event.key === 'Escape' && lightbox.classList.contains('open')) closeLightbox();
  });

  if (!gallery) {
    if (empty) empty.hidden = false;
    return;
  }

  document.title = gallery.title + ' Gallery | The Water Traveler';
  title.textContent = gallery.title;
  intro.textContent = gallery.intro;
  hero.style.backgroundImage = "url('" + gallery.hero + "')";
  heading.textContent = gallery.title + ' Gallery';
  count.textContent = gallery.images.length + ' photos';

  if (description && gallery.description) {
    const descriptionFragment = document.createDocumentFragment();
    gallery.description.forEach(item => {
      const node = document.createElement(item.heading ? 'h3' : 'p');
      node.textContent = item.heading || item;
      descriptionFragment.appendChild(node);
    });
    description.appendChild(descriptionFragment);
  }

  const fragment = document.createDocumentFragment();
  gallery.images.forEach((src, index) => {
    const link = document.createElement('a');
    link.href = src;
    link.setAttribute('aria-label', 'Open ' + gallery.title + ' photo ' + (index + 1));
    const img = document.createElement('img');
    img.src = src;
    img.alt = gallery.title + ' photo ' + (index + 1);
    img.loading = 'lazy';
    link.addEventListener('click', event => {
      event.preventDefault();
      openLightbox(src, img.alt);
    });
    link.appendChild(img);
    fragment.appendChild(link);
  });
  grid.appendChild(fragment);

  if (gallery.id === 'sf-just-dreaming') {
    const weddingSection = document.createElement('section');
    weddingSection.className = 'px py bg-white';
    weddingSection.innerHTML = '<div class="tag">Events</div><h2 class="title">Weddings</h2><p class="body-text">' + TWT_WEDDING_IMAGES.length + ' photos</p><div class="gallery-page-grid"></div>';
    const weddingGrid = weddingSection.querySelector('.gallery-page-grid');

    TWT_WEDDING_IMAGES.forEach((src, index) => {
      const link = document.createElement('a');
      link.href = src;
      link.setAttribute('aria-label', 'Open wedding photo ' + (index + 1));
      const img = document.createElement('img');
      img.src = src;
      img.alt = 'Wedding photo ' + (index + 1);
      img.loading = 'lazy';
      link.addEventListener('click', event => {
        event.preventDefault();
        openLightbox(src, img.alt);
      });
      link.appendChild(img);
      weddingGrid.appendChild(link);
    });

    document.querySelector('footer').before(weddingSection);
  }
})();
